-- 1. Create table 'user' (quoted as "user" in PostgreSQL)
CREATE TABLE IF NOT EXISTS public."user" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) DEFAULT 'admin',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure role column exists if table was created earlier
ALTER TABLE public."user" ADD COLUMN IF NOT EXISTS role VARCHAR(50) DEFAULT 'admin';

-- 2. Create table 'projects'
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    admin VARCHAR(50) NOT NULL,
    tag VARCHAR(50) DEFAULT 'Digital Art',
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    image TEXT DEFAULT NULL,
    view_count INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure tag, view_count, and image type are updated if table was created earlier
ALTER TABLE public.projects ADD COLUMN IF NOT EXISTS tag VARCHAR(50) DEFAULT 'Digital Art';
ALTER TABLE public.projects ADD COLUMN IF NOT EXISTS view_count INT DEFAULT 0;
ALTER TABLE public.projects ALTER COLUMN image TYPE TEXT;

-- 3. Create table 'site_analytics'
CREATE TABLE IF NOT EXISTS public.site_analytics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_path VARCHAR(255) NOT NULL,
    visitor_id VARCHAR(100) NOT NULL,
    country VARCHAR(100) DEFAULT 'Indonesia',
    duration_seconds INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

