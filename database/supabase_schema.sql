-- 5. Enable Row Level Security (RLS) policies
ALTER TABLE public."user" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_analytics ENABLE ROW LEVEL SECURITY;

-- Policies for "user" table (SELECT, INSERT, UPDATE, DELETE)
DROP POLICY IF EXISTS "Allow public read access to user" ON public."user";
CREATE POLICY "Allow public read access to user" ON public."user" FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert to user" ON public."user";
CREATE POLICY "Allow public insert to user" ON public."user" FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update to user" ON public."user";
CREATE POLICY "Allow public update to user" ON public."user" FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public delete to user" ON public."user";
CREATE POLICY "Allow public delete to user" ON public."user" FOR DELETE USING (true);

-- Policies for "projects" table (SELECT, INSERT, UPDATE, DELETE)
DROP POLICY IF EXISTS "Allow public read access to projects" ON public.projects;
CREATE POLICY "Allow public read access to projects" ON public.projects FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert to projects" ON public.projects;
CREATE POLICY "Allow public insert to projects" ON public.projects FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update to projects" ON public.projects;
CREATE POLICY "Allow public update to projects" ON public.projects FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public delete to projects" ON public.projects;
CREATE POLICY "Allow public delete to projects" ON public.projects FOR DELETE USING (true);

-- Policies for "site_analytics" table
DROP POLICY IF EXISTS "Allow public insert to site_analytics" ON public.site_analytics;
